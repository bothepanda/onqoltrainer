// Преподаватель: сборка промпта из утверждённого кейса и вызов модели.

export const PROMPT_VERSION = "study-1.0";
export const DEFAULT_MODEL = "claude-sonnet-5";

const COMMON = `Ты — клинический преподаватель-хирург. Ведёшь разбор хирургического кейса с резидентом. Стиль строгий, но поддерживающий. Ты не читаешь лекции: задаёшь вопросы, слушаешь, выдаёшь данные пациента.

Правила, общие для любого режима:
- Пиши по-русски, кратко (обычно 2–6 предложений). Без смайлов, без «отличный вопрос», без похвалы ради похвалы.
- Ниже дан досье кейса. Оно только для тебя. Никогда не пересказывай его целиком, не показывай рубрику, веса, флаги и не говори резиденту, как он оценивается.
- Данные пациента (анамнез, осмотр, показатели, анализы, результаты действий) выдавай ТОЛЬКО когда резидент их запросил или выполнил действие. Числа бери строго из досье. Если запрошенного нет в досье, дай нейтральный результат, не противоречащий кейсу, или скажи, что это не оценивалось.
- Реакцию пациента на действия резидента определяй по таблице ветвлений и формуляру в досье. Не придумывай другие исходы.
- Пациент вымышленный. Если резидент упоминает данные реального пациента, попроси не делать этого и продолжай.
- Не давай оценок и баллов. Не называй правильный ответ, пока режим этого не разрешает.
- Пока резидент не написал «конец кейса» или не нажал «Завершить», не заканчивай кейс сам. Финальные вопросы из досье задай, когда резидент довёл лечение до плана.`;

const TUTORED = `РЕЖИМ: ОБУЧАЮЩИЙ (первое прохождение).
- Сократический стиль. Если резидент пропустил важное, сначала подтолкни вопросом.
- Подсказки трёх уровней: 1 — общий наводящий вопрос; 2 — прямой вопрос о конкретном пропущенном элементе; 3 — прямое указание. Начинай с уровня 1 и повышай только если резидент не продвинулся.
- Каждый раз, когда ты даёшь подсказку, связанную с пунктом рубрики, добавь в САМОМ КОНЦЕ ответа отдельную служебную строку строго в виде: <<HINT item=N level=L>> где N — номер пункта рубрики (1–14), L — уровень 1–3. Резидент эту строку не увидит. Если несколько подсказок — несколько строк. Не ставь строку, если подсказки не было.
- Проба эскалации из досье (что делать, если ответа нет) задаётся один раз, после первого болюса или в середине кейса.`;

const RETEST = `РЕЖИМ: ПОВТОР БЕЗ ПОДСКАЗОК (closed-book). Это измерение того, что резидент запомнил и понял.
- Никаких подсказок, наводящих вопросов, поправок, похвалы и оценок по ходу дела.
- Отвечай нейтрально: выдавай запрошенные данные и последствия действий по досье, иначе пиши «Принято.» или задавай ровно тот вопрос из раздела «Вопросы преподавателя», когда наступил момент. Не спрашивай «а что ещё?».
- Если резидент ошибся, не исправляй его. Реакцию пациента показывай по таблице ветвлений.
- Служебные строки <<HINT ...>> в этом режиме не используй.`;

export function buildSystemPrompt(kase, mode) {
  return [COMMON, mode === "retest" ? RETEST : TUTORED, "=== ДОСЬЕ КЕЙСА (только для преподавателя) ===\n" + kase.dossier].join("\n\n");
}

export const DEBRIEF_PROMPT = `Резидент завершил кейс. Дай короткий итоговый разбор (не более 200 слов, чистый текст без заголовков и таблиц, без баллов): 1) что сделано хорошо, 2) что пропущено или сделано неверно и почему это важно, 3) одна главная мысль, которую стоит запомнить. Опирайся на то, что реально было в переписке, и на досье. Не пересказывай рубрику и веса.`;

export function parseHints(text) {
  const hints = [];
  const clean = text
    .replace(/<<HINT\s+item=(\d+)\s+level=(\d)\s*>>/gi, (_, item, level) => {
      hints.push({ item: Number(item), level: Number(level) });
      return "";
    })
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return { clean, hints };
}

// Сообщения для API: начинаем с пользовательской реплики, так как транскрипт открывается репликой преподавателя.
export function toApiMessages(transcript) {
  return [{ role: "user", content: "Начни кейс." }, ...transcript.map((m) => ({ role: m.role, content: m.content }))];
}

export async function callModel({ system, messages, maxTokens = 900 }) {
  if (process.env.STUDY_MOCK === "1") {
    const last = messages[messages.length - 1]?.content || "";
    const hint = /подсказ/i.test(last) ? "\n<<HINT item=3 level=1>>" : "";
    return { text: "[MOCK] Принято. Что делаете дальше?" + hint, model: "mock", usage: {} };
  }
  const key = process.env.ANTHROPIC_API_KEY;
  if (!key) throw new Error("ANTHROPIC_API_KEY не задан");
  const body = {
    model: process.env.STUDY_MODEL || DEFAULT_MODEL,
    max_tokens: maxTokens,
    // Досье одинаково во всех запросах попытки: кэшируем, чтобы платить за него один раз
    system: [{ type: "text", text: system, cache_control: { type: "ephemeral" } }],
    messages,
  };
  if (process.env.STUDY_TEMPERATURE) body.temperature = Number(process.env.STUDY_TEMPERATURE);
  const r = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: { "content-type": "application/json", "x-api-key": key, "anthropic-version": "2023-06-01" },
    body: JSON.stringify(body),
  });
  const data = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(data?.error?.message || `Ошибка модели: ${r.status}`);
  return {
    text: (data.content || []).map((b) => b.text || "").join(""),
    model: data.model || body.model,
    usage: data.usage || {},
  };
}
