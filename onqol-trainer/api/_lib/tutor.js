// Проверки ответа кодом (одинаковы для любой модели).
// Оценочное слово в начале предложения: «Хорошо.», «Верно, …». Внутри предложения («сознание хорошее») не считается.
const EVAL_RE = /(^|[.!?…\n]\s*)(верно|правильно|именно|хорошо|отлично|согласен|разумно|логично|молодец)(?![а-яё])/i;
export const hasEvalWords = (text) => EVAL_RE.test(text);
export const REWRITE_NOTE = "[СЛУЖЕБНО: в твоей последней реплике есть оценочное слово («верно», «хорошо», «именно» и подобные). Перепиши эту реплику без оценок: реагируй нейтрально («Принято», «Понятно») и сохрани всё остальное, включая служебные строки <<HINT ...>>, если они были.]";

// Разбор не получился, если модель повторила фразу про кнопку или ответила слишком коротко
export const debriefFailed = (text) => text.length < 200 || /нажмите кнопку|только через кнопку|не могу так поступить|попытк\S* обойти/i.test(text);

// Текстовая команда завершить кейс, в том числе с опечатками («заверщшить кейс», «нет, закончить кейс»)
const FINISH_TEXT_RE = /^(?:(?:нет|да|всё|все|ок|хорошо)[,.\s]+)?(?:(?:зав|закон|конч|конец)\S*\s+(?:кейс\S*|случ\S*)|(?:(?:зав|закон|конч)\S*[,\s]+)?дай\s+разбор|разбор)[.!\s]*$/i;
export const isFinishText = (text) => text.length <= 40 && FINISH_TEXT_RE.test(text.trim());

export function parseHints(text) {
  const hints = [];
  const clean = text
    .replace(/<<HINT\s+item=(\d+)\s+level=(\d)\s*>>/gi, (_, item, level) => {
      hints.push({ item: Number(item), level: Number(level) });
      return "";
    })
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return { clean, hints };
}

// Сообщения для API: начинаем с пользовательской реплики, так как транскрипт открывается репликой преподавателя.
// annotateHints: для итогового разбора помечаем реплики, где была подсказка (модели это нужно, чтобы честно различать «сам» и «после подсказки»)
export function toApiMessages(transcript, { annotateHints = false } = {}) {
  const note = (m) =>
    annotateHints && m.hints?.length
      ? `\n[СЛУЖЕБНО: здесь была подсказка: ${m.hints.map((h) => `уровень ${h.level}, пункт ${h.item}`).join("; ")}]`
      : "";
  return [{ role: "user", content: "Начни кейс." }, ...transcript.map((m) => ({ role: m.role, content: m.content + note(m) }))];
}

let client;
const getClient = () => (client ||= new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY }));

// thinking: "disabled" отключает размышление (нужно оценщику: размышление делит с ответом один лимит токенов).
// timeoutMs и retries выбираются под лимит функции на Vercel (60 с): худший случай = timeoutMs × (retries + 1).
// temperature намеренно не поддерживается: на Sonnet 5 параметр возвращает 400.
export async function callModel({ system, messages, maxTokens = 2000, thinking, timeoutMs = 25000, retries = 1, cacheConversation = false, role = "tutor", residentId = "" }) {
  if (process.env.STUDY_MOCK === "1") {
    const last = messages[messages.length - 1]?.content || "";
    if (system.includes("НЕЗАВИСИМЫЙ ОЦЕНЩИК")) {
      // Заглушка оценщика: цитата берётся из первой реплики резидента; для пункта 14 цитата нарочно выдумана
      const quote = (last.match(/\[#\d+ РЕЗИДЕНТ[^\]]*\] ([^\n]{5,60})/) || [])[1] || "";
      const items = Array.from({ length: 14 }, (_, k) => {
        const n = k + 1;
        const score = n === 14 ? 2 : n % 3 === 0 ? 0 : n % 3 === 1 ? 2 : 1;
        return { n, score, hint_level: score === 1 ? 1 : 0, evidence: score === 0 ? "" : n === 14 ? "ЭТОЙ ЦИТАТЫ В ПЕРЕПИСКЕ НЕТ" : quote, reason: "mock" };
      });
      return { text: JSON.stringify({ items, flags: { c1: { value: false, evidence: "" }, c2: { value: false, evidence: "" } } }), model: "mock", usage: {}, stop_reason: "end_turn" };
    }
    const hint = /подсказ/i.test(last) ? "\n<<HINT item=3 level=1>>" : "";
    return { text: "[MOCK] Принято. Что делаете дальше?" + hint, model: "mock", usage: {}, stop_reason: "end_turn" };
  }
  if (!process.env.ANTHROPIC_API_KEY) throw new Error("ANTHROPIC_API_KEY не задан");
  const body = {
    model: modelFor(role, residentId),
    max_tokens: maxTokens,
    // Досье одинаково во всех запросах попытки: кэшируем, чтобы платить за него один раз
    system: [{ type: "text", text: system, cache_control: { type: "ephemeral" } }],
    messages,
  };
  if (thinking === "disabled") body.thinking = { type: "disabled" };
  // Кэш переписки: точка кэширования на последней реплике. Следующий ход прочитает уже записанное
  // (в 10 раз дешевле обычного входа) и запишет только два новых сообщения. Только для хода диалога:
  // у оценщика и разбора переписка уходит один раз, кэшировать её невыгодно.
  if (cacheConversation && messages.length) {
    const last = messages[messages.length - 1];
    const text = typeof last.content === "string" ? last.content : "";
    body.messages = [...messages.slice(0, -1), { role: last.role, content: [{ type: "text", text, cache_control: { type: "ephemeral" } }] }];
  }
  let msg;
  try {
    msg = await getClient().messages.create(body, { timeout: timeoutMs, maxRetries: retries });
  } catch (err) {
    if (err instanceof Anthropic.APIConnectionTimeoutError) throw new Error("Модель не ответила вовремя", { cause: err });
    if (err instanceof Anthropic.RateLimitError) throw new Error("Лимит запросов к модели, повторите через минуту", { cause: err });
    if (err instanceof Anthropic.APIError) throw new Error(`Ошибка модели ${err.status}: ${err.message}`, { cause: err });
    throw err;
  }
  if (msg.stop_reason === "refusal") throw new Error("Модель отклонила запрос (refusal)");
  return {
    text: msg.content.filter((b) => b.type === "text").map((b) => b.text).join(""),
    model: msg.model,
    usage: msg.usage || {},
    stop_reason: msg.stop_reason || null,
  };
}
