const RETEST = `РЕЖИМ: ПОВТОР БЕЗ ПОДСКАЗОК (closed-book). Это измерение того, что резидент запомнил и понял.
- Никаких подсказок, наводящих вопросов, поправок, похвалы и оценок по ходу дела.
- Отвечай нейтрально: выдавай запрошенные данные и последствия действий по досье, иначе пиши «Принято.» или задавай ровно тот вопрос из раздела «Вопросы преподавателя», когда наступил момент. Не спрашивай «а что ещё?».
- Неоднозначные назначения выполняй буквально и без уточнений («500 мл в течение часа» — это медленная инфузия, не болюс) и показывай последствия по таблице.
- Если резидент ошибся, не исправляй его.
- Если резидент просит подсказку или оценку, ответь: «В этом режиме подсказок нет.»
- Служебные строки <<HINT ...>> не используй.`;

export function buildSystemPrompt(kase, mode) {
  return [COMMON, mode === "retest" ? RETEST : TUTORED, "=== ДОСЬЕ КЕЙСА (только для преподавателя) ===\n" + kase.dossier].join("\n\n");
}

export const DEBRIEF_PROMPT = `Резидент завершил кейс. Дай короткий итоговый разбор (не более 200 слов, чистый текст без заголовков и таблиц, без баллов и без упоминания рубрики).
Опирайся ТОЛЬКО на то, что резидент сам написал или запросил. Различай три вещи: 1) что он сделал сам, без наводящих вопросов; 2) что он сделал только после наводящего вопроса или подсказки; 3) что он не сделал. Не засчитывай как «сам» то, что первым сказал или выдал преподаватель (данные, расчёты, интерпретацию, названия диагнозов), и не хвали за то, чего в переписке нет. Если резидент сначала ошибся, а потом исправился после подсказки, скажи об этом прямо.
Заверши одной главной мыслью, которую стоит запомнить.`;

export function parseHints(text) {
  const hints = [];
  const clean = text
    .replace(/<<HINT\s+item=(\d+)\s+level=(\d)\s*>>/gi, (_, item, level) => {
      hints.push({ item: Number(item), level: Number(level) });
      return "";
    })
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return { clean, hints };
}

// Сообщения для API: начинаем с пользовательской реплики, так как транскрипт открывается репликой преподавателя.
// annotateHints: для итогового разбора помечаем реплики, где была подсказка (модели это нужно, чтобы честно различать «сам» и «после подсказки»)
export function toApiMessages(transcript, { annotateHints = false } = {}) {
  const note = (m) =>
    annotateHints && m.hints?.length
      ? `\n[СЛУЖЕБНО: здесь была подсказка: ${m.hints.map((h) => `уровень ${h.level}, пункт ${h.item}`).join("; ")}]`
      : "";
  return [{ role: "user", content: "Начни кейс." }, ...transcript.map((m) => ({ role: m.role, content: m.content + note(m) }))];
}

export async function callModel({ system, messages, maxTokens = 2000 }) {
  if (process.env.STUDY_MOCK === "1") {
    const last = messages[messages.length - 1]?.content || "";
    const hint = /подсказ/i.test(last) ? "\n<<HINT item=3 level=1>>" : "";
    return { text: "[MOCK] Принято. Что делаете дальше?" + hint, model: "mock", usage: {}, stop_reason: "end_turn" };
  }
  const key = process.env.ANTHROPIC_API_KEY;
  if (!key) throw new Error("ANTHROPIC_API_KEY не задан");
  const body = {
    model: process.env.STUDY_MODEL || DEFAULT_MODEL,
    max_tokens: maxTokens,
    // Досье одинаково во всех запросах попытки: кэшируем, чтобы платить за него один раз
    system: [{ type: "text", text: system, cache_control: { type: "ephemeral" } }],
    messages,
  };
  if (process.env.STUDY_TEMPERATURE) body.temperature = Number(process.env.STUDY_TEMPERATURE);
  const r = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: { "content-type": "application/json", "x-api-key": key, "anthropic-version": "2023-06-01" },
    body: JSON.stringify(body),
  });
  const data = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(data?.error?.message || `Ошибка модели: ${r.status}`);
  return {
    text: (data.content || []).map((b) => b.text || "").join(""),
    model: data.model || body.model,
    usage: data.usage || {},
    stop_reason: data.stop_reason || null,
  };
}
